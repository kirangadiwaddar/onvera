  add column if not exists password_hash text,
  add column if not exists password_plain text;

create or replace function public.sync_identity_sequences()
returns void
language plpgsql
security definer
as $$
begin
  perform setval(
    pg_get_serial_sequence('public.teams', 'id'),
    coalesce((select max(id) from public.teams), 1),
    true
  );

  perform setval(
    pg_get_serial_sequence('public.projects', 'id'),
    coalesce((select max(id) from public.projects), 1),
    true
  );
end;
$$;
